//! Tokens.

use std::fmt;

/// A token. The command tokens (`Assume`, `DeclareConst`, ...) are not made
/// by the lexer, which reads command names as symbols; the command parser
/// maps the symbols to them.
#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]
pub enum Token {
    Eof,
    Assert,
    Assume,
    AssumePush,
    Attribute,
    BoolType,
    BinaryLiteral,
    CheckSat,
    CheckSatAssuming,
    DecimalLiteral,
    DeclareConst,
    DeclareConsts,
    DeclareDatatype,
    DeclareDatatypes,
    DeclareFun,
    DeclareParameterizedConst,
    DeclareRule,
    DeclareSort,
    Define,
    DefineConst,
    DefineFun,
    DefineSort,
    Echo,
    /// `eo::define`
    EvalDefine,
    Exit,
    HexLiteral,
    Include,
    IntegerLiteral,
    Keyword,
    Let,
    Lparen,
    Par,
    Program,
    QuotedSymbol,
    RationalLiteral,
    Reference,
    Reset,
    ResetAssertions,
    Rparen,
    SetInfo,
    SetLogic,
    SetOption,
    /// An SMT-LIB command that only asks the solver for output, such as
    /// `get-model`.
    Smt2QueryCommand,
    Step,
    StepPop,
    StringLiteral,
    Symbol,
    Type,
    UnterminatedQuotedSymbol,
    UnterminatedStringLiteral,
}

impl fmt::Display for Token {
    /// The token's name in Ethos, as it appears in error messages.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Token::Eof => "EOF",
            Token::Assert => "ASSERT",
            Token::Assume => "ASSUME",
            Token::AssumePush => "ASSUME_PUSH",
            Token::Attribute => "ATTRIBUTE",
            Token::BoolType => "BOOL_TYPE",
            Token::BinaryLiteral => "BINARY_LITERAL",
            Token::CheckSat => "CHECK_SAT",
            Token::CheckSatAssuming => "CHECK_SAT_ASSUMING",
            Token::DecimalLiteral => "DECIMAL_LITERAL",
            Token::DeclareConst => "DECLARE_CONST",
            Token::DeclareConsts => "DECLARE_CONSTS",
            Token::DeclareDatatype => "DECLARE_DATATYPE",
            Token::DeclareDatatypes => "DECLARE_DATATYPES",
            Token::DeclareFun => "DECLARE_FUN",
            Token::DeclareParameterizedConst => "DECLARE_PARAMETERIZED_CONST",
            Token::DeclareRule => "DECLARE_RULE",
            Token::DeclareSort => "DECLARE_SORT",
            Token::Define => "DEFINE",
            Token::DefineConst => "DEFINE_CONST",
            Token::DefineFun => "DEFINE_FUN",
            Token::DefineSort => "DEFINE_SORT",
            Token::Echo => "ECHO",
            Token::EvalDefine => "EVAL_DEFINE",
            Token::Exit => "EXIT",
            Token::HexLiteral => "HEX_LITERAL",
            Token::Include => "INCLUDE",
            Token::IntegerLiteral => "INTEGER_LITERAL",
            Token::Keyword => "KEYWORD",
            Token::Let => "LET",
            Token::Lparen => "LPAREN",
            Token::Par => "PAR",
            Token::Program => "PROGRAM",
            Token::QuotedSymbol => "QUOTED_SYMBOL",
            Token::RationalLiteral => "RATIONAL_LITERAL",
            Token::Reference => "REFERENCE",
            Token::Reset => "RESET",
            Token::ResetAssertions => "RESET_ASSERTIONS",
            Token::Rparen => "RPAREN",
            Token::SetInfo => "SET_INFO",
            Token::SetLogic => "SET_LOGIC",
            Token::SetOption => "SET_OPTION",
            Token::Smt2QueryCommand => "SMT2_QUERY_COMMAND",
            Token::Step => "STEP",
            Token::StepPop => "STEP_POP",
            Token::StringLiteral => "STRING_LITERAL",
            Token::Symbol => "SYMBOL",
            Token::Type => "TYPE",
            Token::UnterminatedQuotedSymbol => "UNTERMINATED_QUOTED_SYMBOL",
            Token::UnterminatedStringLiteral => "UNTERMINATED_STRING_LITERAL",
        })
    }
}
